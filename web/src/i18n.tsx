type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: keyof typeof STRINGS | string) => string;
  pick: (en: string | null | undefined, hi: string | null | undefined) => string;
  name: (obj: { name_en?: string; name_hi?: string } | null | undefined) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("kisan.lang") as Lang) || "en");

  useEffect(() => {
    document.documentElement.lang = lang === "hi" ? "hi" : "en";
    localStorage.setItem("kisan.lang", lang);
  }, [lang]);

  const value = useMemo<Ctx>(() => {
    const t = (key: string) => STRINGS[key]?.[lang] ?? key;
    const pick = (en?: string | null, hi?: string | null) => (lang === "hi" ? hi || en || "" : en || hi || "");
    const name = (obj?: { name_en?: string; name_hi?: string } | null) =>
      lang === "hi" ? obj?.name_hi || obj?.name_en || "" : obj?.name_en || obj?.name_hi || "";
    return { lang, setLang: setLangState, t, pick, name };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
